type TranslationKey = keyof (typeof translations)['id'];

let currentLanguage: Language = 'id';
const listeners = new Set<() => void>();

function subscribe(callback: () => void): () => void {
    listeners.add(callback);

    return () => listeners.delete(callback);
}

function notify(): void {
    listeners.forEach((listener) => listener());
}

export function initializeLanguage(): void {
    if (typeof window === 'undefined') {
        return;
    }

    try {
        const savedLanguage = localStorage.getItem('language');

        if (languages.includes(savedLanguage as Language)) {
            currentLanguage = savedLanguage as Language;
        }
    } catch {
        currentLanguage = 'id';
    }

    document.documentElement.lang = languageLocales[currentLanguage];
    document.documentElement.dir = currentLanguage === 'ar' ? 'rtl' : 'ltr';
    notify();
}

export function setLanguage(language: Language): void {
    currentLanguage = language;
    document.documentElement.lang = languageLocales[language];
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';

    try {
        localStorage.setItem('language', language);
    } catch {
        // The current session still uses the selected language if storage is unavailable.
    }

    notify();
}

export function useLang(): {
    language: Language;
    setLanguage: (language: Language) => void;
    t: (key: TranslationKey) => string;
} {
    const language = useSyncExternalStore<Language>(
        subscribe,
        () => currentLanguage,
        () => 'id',
    );

    return {
        language,
        setLanguage,
        t: (key) => translations[language][key],
    };
}
